#!/usr/bin/env node
/**
 * build-markdown.mjs — generate index.md from the data already in script.js.
 *
 *   npm run markdown
 *
 * index.md is the plain-Markdown mirror of the homepage, linked from <head>
 * and from the ARD catalog so agents can read the site without parsing HTML.
 * Generating it (rather than hand-writing it) means the copy on the page and
 * the copy an assistant reads cannot drift apart.
 *
 * script.js is a browser IIFE, so it cannot simply be imported. Instead the
 * two data literals are located by brace matching and evaluated on their own.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'script.js'), 'utf8');

/** Pull `const <name> = {…};` out of the source and evaluate the literal. */
function extract(name) {
  const start = source.indexOf(`const ${name} = {`);
  if (start === -1) throw new Error(`Could not find "const ${name} = {" in script.js`);

  const open = source.indexOf('{', start);
  let depth = 0;
  let inStr = null;
  let escaped = false;

  for (let i = open; i < source.length; i++) {
    const ch = source[i];

    if (inStr) {
      if (escaped) escaped = false;
      else if (ch === '\\') escaped = true;
      else if (ch === inStr) inStr = null;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === '`') { inStr = ch; continue; }
    if (ch === '/' && source[i + 1] === '/') { i = source.indexOf('\n', i); continue; }
    if (ch === '{') depth++;
    else if (ch === '}') {
      depth--;
      if (depth === 0) {
        const literal = source.slice(open, i + 1);
        return new Function(`return (${literal});`)();
      }
    }
  }
  throw new Error(`Unbalanced braces while reading "${name}"`);
}

const projects = extract('projects');
const translations = extract('translations');

const cfg = JSON.parse(readFileSync(join(root, 'site.config.json'), 'utf8'));
const waDigits = cfg.contact.phoneE164.replace(/[^\d]/g, '');

const pick = (value, lang) =>
  typeof value === 'string' ? value : value && typeof value === 'object' ? value[lang] || value.en || '' : '';

function projectBlock(project, lang) {
  const m = project.meta || {};
  const facts = [pick(m.location, lang), m.year, pick(m.type, lang), m.area].filter(Boolean);
  const credit = pick(m.credit, lang);

  const lines = [`### ${pick(project.title, lang)}`, ''];
  if (facts.length) lines.push(`*${facts.join(' · ')}*`, '');
  lines.push(pick(project.description, lang), '');
  if (credit) lines.push(`${lang === 'es' ? 'Fotografía' : 'Photography'}: ${credit}`, '');
  lines.push(`${lang === 'es' ? 'Imágenes' : 'Images'}: ${(project.images || []).length}`, '');
  return lines.join('\n');
}

function render(lang) {
  const d = translations[lang];
  const out = [];

  out.push(`# ${d.brandName}`, '');
  out.push(`> ${d.heroEyebrow}`, '');
  out.push(`## ${d.heroTitle}`, '', d.heroLead, '');

  const sections = [
    ['interior', d.interiorTitle, d.interiorLead],
    ['architecture', d.architectureTitle, d.architectureLead],
    ['permits', d.permitsTitle, d.permitsLead],
  ];

  for (const [key, title, lead] of sections) {
    out.push(`## ${title}`, '', lead, '');
    for (const project of projects[key] || []) out.push(projectBlock(project, lang));
  }

  out.push(`## ${d.studioTitle}`, '', d.studioLead, '');
  for (const n of [1, 2, 3]) {
    out.push(`**${d[`studioValue${n}Title`]}** — ${d[`studioValue${n}Body`]}`, '');
  }

  out.push(`### ${d.processTitle}`, '');
  for (const n of [1, 2, 3, 4]) {
    out.push(`${n}. **${d[`process${n}Title`]}** — ${d[`process${n}Body`]}`);
  }
  out.push('', `${d.areasLabel}: ${d.areasList}`, '');

  out.push(`## ${d.contactTitle}`, '', d.contactLead, '');
  out.push(`- WhatsApp: https://wa.me/${waDigits}`);
  out.push(`- ${d.labelPhone}: ${cfg.contact.phoneDisplay}`);
  out.push(`- ${d.labelEmail}: ${cfg.contact.email}`);
  out.push(`- Instagram: https://www.instagram.com/${cfg.brand.instagramHandle}/`);
  out.push(`- ${d.labelStudio}: ${d.labelStudioValue}`, '');

  return out.join('\n');
}

const markdown = [
  '<!-- Generated by scripts/build-markdown.mjs from script.js — do not edit by hand. -->',
  '',
  render('en'),
  '---',
  '',
  render('es'),
].join('\n');

writeFileSync(join(root, 'index.md'), markdown.replace(/\n{3,}/g, '\n\n') + '\n');
console.log(`✓ index.md written (${markdown.length.toLocaleString()} chars, EN + ES)`);
